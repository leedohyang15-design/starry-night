def _vec(ra_deg, dec_deg):
    r, d = math.radians(ra_deg), math.radians(dec_deg)
    return (math.cos(d) * math.cos(r), math.cos(d) * math.sin(r), math.sin(d))


def _norm(v):
    m = math.hypot(*v) or 1
    return (v[0] / m, v[1] / m, v[2] / m)


def _dot(a, b): return a[0]*b[0] + a[1]*b[1] + a[2]*b[2]
def _cross(a, b): return (a[1]*b[2]-a[2]*b[1], a[2]*b[0]-a[0]*b[2], a[0]*b[1]-a[1]*b[0])


def project(stars):
    """RA/Dec → 100×100 뷰박스.

    v0.23: 사용자 레퍼런스(Constellation Effect)와 같은 **별자리 중심 입체 투영**으로 교체.
    구 방식(적경×cos·적위를 그대로 직교 배치)은 별자리가 클수록 좌우로 늘어났다.
    별의 **순서와 개수는 그대로**라 카드의 si 참조는 영향을 받지 않는다.
    """
    vs = [_vec(s[1], s[2]) for s in stars]
    c = _norm(tuple(sum(v[i] for v in vs) for i in range(3)))
    east = _cross((0, 0, 1), c)
    east = _norm(east) if math.hypot(*east) > 1e-6 else (1, 0, 0)
    north = _cross(c, east)
    raw = []
    for v in vs:
        f = 2 / (1 + _dot(v, c))
        raw.append((-f * _dot(v, east), -f * _dot(v, north)))
    xs = [p[0] for p in raw]; ys = [p[1] for p in raw]
    span_x = max(xs) - min(xs); span_y = max(ys) - min(ys)
    scale = 76.0 / max(span_x, span_y, 1e-9)
    off_x = (100 - span_x * scale) / 2 - min(xs) * scale
    off_y = (100 - span_y * scale) / 2 - min(ys) * scale
    return [[round(p[0] * scale + off_x, 1), round(p[1] * scale + off_y, 1), stars[i][3]]
            for i, p in enumerate(raw)]


